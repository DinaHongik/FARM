"""
Setup TARGE to Use FARM Dataset

This script copies the converted FARM data to TARGE's expected directory structure.
Creates a backup of original TARGE data and sets up FARM data for evaluation.

Directory structure created:
    Targe/data/dataset_farm/
    ├── gold/
    │   ├── test_recipe.json
    │   ├── test_trigger.json
    │   └── test_action.json
    ├── noisy/
    │   ├── test_recipe.json
    │   ├── test_trigger.json
    │   └── test_action.json
    └── gold/  (oneshot goes here as one-shot variant)
        ├── test_recipe_one_shot.json
        ├── test_trigger_one_shot.json
        └── test_action_one_shot.json

Usage:
    python setup_targe_with_farm_data.py [--copy-to-targe]

Options:
    --copy-to-targe: Actually copy files to TARGE directory (default: dry run)
"""

import json
import shutil
import argparse
from pathlib import Path


def setup_targe_farm_dataset(dry_run: bool = True):
    """
    Set up TARGE to use FARM dataset for evaluation.

    Args:
        dry_run: If True, only print what would be done without copying
    """
    # Paths
    project_root = Path(__file__).parent.parent.parent
    farm_converted_dir = Path(__file__).parent / "farm_as_targe_format"
    targe_dir = project_root / "Targe"
    targe_data_dir = targe_dir / "data" / "dataset_farm"  # New directory for FARM data

    print("=" * 60)
    print("Setup TARGE with FARM Dataset")
    print("=" * 60)
    print(f"Source: {farm_converted_dir}")
    print(f"Target: {targe_data_dir}")
    print(f"Mode: {'DRY RUN' if dry_run else 'ACTUAL COPY'}")
    print()

    # Define file mappings
    # (source_file, target_subdir, target_filename)
    file_mappings = [
        # Gold set
        ("test_gold_recipe.json", "gold", "test_recipe.json"),
        ("test_gold_trigger.json", "gold", "test_trigger.json"),
        ("test_gold_action.json", "gold", "test_action.json"),

        # Noisy set
        ("test_noisy_recipe.json", "noisy", "test_recipe.json"),
        ("test_noisy_trigger.json", "noisy", "test_trigger.json"),
        ("test_noisy_action.json", "noisy", "test_action.json"),

        # One-shot set (placed in gold directory with _one_shot suffix)
        ("test_oneshot_recipe.json", "gold", "test_recipe_one_shot.json"),
        ("test_oneshot_trigger.json", "gold", "test_trigger_one_shot.json"),
        ("test_oneshot_action.json", "gold", "test_action_one_shot.json"),
    ]

    # Check source files exist
    print("Checking source files...")
    missing_files = []
    for src_file, _, _ in file_mappings:
        src_path = farm_converted_dir / src_file
        if src_path.exists():
            print(f"  [OK] {src_file}")
        else:
            print(f"  [MISSING] {src_file}")
            missing_files.append(src_file)

    if missing_files:
        print(f"\nError: {len(missing_files)} source files missing!")
        print("Run convert_farm_to_targe.py first.")
        return False

    # Create directory structure and copy files
    print("\nSetting up directory structure...")

    for src_file, target_subdir, target_filename in file_mappings:
        src_path = farm_converted_dir / src_file
        target_dir = targe_data_dir / target_subdir
        target_path = target_dir / target_filename

        if dry_run:
            print(f"  Would copy: {src_file} -> {target_path}")
        else:
            target_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src_path, target_path)
            print(f"  Copied: {src_file} -> {target_path}")

    # Create a README in the new directory
    readme_content = """# FARM Dataset in TARGE Format

This directory contains the FARM test dataset converted to TARGE's expected format.

## Contents

- `gold/` - High-quality test samples (500 samples)
- `noisy/` - Noisy test samples (500 samples)
- `gold/test_*_one_shot.json` - One-shot test samples (200 samples)

## Format

Each JSON file contains entries in TARGE's expected format:

```json
{
    "input": "User query describing automation",
    "output": "IF {TriggerChannel} {TriggerFunction} THEN {ActionChannel} {ActionFunction}",
    "score": 0.8,
    "instruction": "..."
}
```

## Usage with TARGE

To use this data with TARGE's evaluation scripts, update the data path in TARGE's config
or copy these files to replace the original test data.

## Generated by

This data was generated using:
```
python eval/targe_comparison/convert_farm_to_targe.py
python eval/targe_comparison/setup_targe_with_farm_data.py
```
"""

    readme_path = targe_data_dir / "README.md"
    if dry_run:
        print(f"\n  Would create: {readme_path}")
    else:
        targe_data_dir.mkdir(parents=True, exist_ok=True)
        with open(readme_path, 'w') as f:
            f.write(readme_content)
        print(f"\n  Created: {readme_path}")

    # Summary
    print("\n" + "=" * 60)
    if dry_run:
        print("DRY RUN COMPLETE")
        print("To actually copy files, run with --copy-to-targe flag")
    else:
        print("SETUP COMPLETE")
        print(f"\nFARM data is now available at: {targe_data_dir}")
        print("\nTo use with TARGE:")
        print("  1. Update TARGE's config to point to 'data/dataset_farm'")
        print("  2. Or copy files from dataset_farm to dataset (backup original first)")

    return True


def show_comparison_stats():
    """Show statistics comparing original TARGE and converted FARM data."""
    project_root = Path(__file__).parent.parent.parent

    # TARGE original data
    targe_gold = project_root / "Targe" / "data" / "dataset" / "gold" / "test_recipe.json"
    # FARM converted data
    farm_gold = Path(__file__).parent / "farm_as_targe_format" / "test_gold_recipe.json"

    print("\n" + "=" * 60)
    print("Dataset Comparison")
    print("=" * 60)

    if targe_gold.exists():
        with open(targe_gold) as f:
            targe_data = json.load(f)
        print(f"TARGE Gold Test Set: {len(targe_data)} samples")

    if farm_gold.exists():
        with open(farm_gold) as f:
            farm_data = json.load(f)
        print(f"FARM Gold Test Set: {len(farm_data)} samples")

        # Show sample
        print("\nSample FARM entry (converted):")
        print(json.dumps(farm_data[0], indent=2))


def main():
    parser = argparse.ArgumentParser(
        description="Setup TARGE to use FARM dataset for comparison"
    )
    parser.add_argument(
        "--copy-to-targe",
        action="store_true",
        help="Actually copy files (default is dry run)"
    )
    parser.add_argument(
        "--stats",
        action="store_true",
        help="Show dataset statistics"
    )

    args = parser.parse_args()

    if args.stats:
        show_comparison_stats()
    else:
        dry_run = not args.copy_to_targe
        setup_targe_farm_dataset(dry_run=dry_run)


if __name__ == "__main__":
    main()
